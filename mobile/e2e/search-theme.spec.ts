import { expect, test } from '@playwright/test'

test('公开样本预览、跨页高亮跳转、过滤和手动正文搜索', async ({ page }) => {
  page.on('dialog', (dialog) => dialog.accept())
  await page.goto('/')
  await page.getByRole('button', { name: '选择并确认保存位置' }).click()
  await page.getByRole('button', { name: '载入公开测试数据' }).click()
  await expect(page.getByRole('dialog')).toContainText('2 个模组')
  await expect(page.getByRole('dialog')).toContainText('4 个场次')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('heading', { name: '暂无场次' })).toBeVisible()
  await page.getByRole('button', { name: '载入公开测试数据' }).click()
  await page.getByRole('button', { name: '确认覆盖并导入' }).click()
  await page.getByRole('button', { name: /雾港调查.*第一场：灯塔线索/ }).click()
  const query = page.getByRole('searchbox', { name: '搜索整场正文' })
  const results = page.getByRole('region', { name: '搜索结果' })
  await query.fill('灯塔')
  await expect(results.getByRole('status')).toContainText('匹配 3 条')
  await expect(page.locator('.messages mark')).toHaveCount(2)
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.locator('[data-message-index="4"]')).toBeFocused()
  await page.getByRole('button', { name: /结果 3 · 正文第 3 页/ }).click()
  await expect(page.locator('[data-message-index="204"]')).toBeFocused()
  await expect(page.locator('.pagination[aria-label="正文分页"]')).toContainText('3 / 3')
  await expect(page.locator('.search-target mark')).toHaveCount(2)
  await expect(page.locator('[data-message-index="203"]')).toBeVisible()
  expect(
    await page.locator('.search-target').evaluate((el) => {
      const box = el.getBoundingClientRect()
      return box.top >= 0 && box.bottom < innerHeight - 70
    })
  ).toBe(true)
  await page.getByRole('button', { name: '上一处', exact: true }).click()
  await expect(page.locator('[data-message-index="104"]')).toBeFocused()
  await query.fill('a+b')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.locator('.search-target mark')).toHaveText('a+b')
  await query.fill('<script>')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.locator('.search-target mark')).toHaveText('<script>')
  await expect(page.locator('.messages script')).toHaveCount(0)
  await query.fill('骰子专用词')
  await expect(results.getByRole('status')).toContainText('匹配 1 条')
  await page.getByLabel('隐藏骰指令').check()
  await expect(results.getByRole('status')).toContainText('匹配 0 条')
  await expect(page.locator('.search-target')).toHaveCount(0)
  await query.fill('港口')
  await expect(results.locator('.search-result')).toHaveCount(20)
  await page.getByRole('button', { name: '下一组结果' }).click()
  await expect(results.locator('.search-result').first()).toContainText('结果 21')
  await page.getByRole('button', { name: '清除搜索' }).click()
  await expect(results).toHaveCount(0)
  await expect(page.locator('.messages mark')).toHaveCount(0)
  await page.getByRole('button', { name: '返回场次', exact: true }).click()
  await page.getByRole('button', { name: /第二场：手动调查笔记/ }).click()
  await query.fill('铜钥匙')
  await expect(results.getByRole('status')).toContainText('匹配 2 条')
  await page.getByRole('button', { name: /结果 2 ·/ }).click()
  await expect(page.locator('.search-target')).toContainText('编号')
})

test('浅深主题保存并重开；320px 深色高亮可见', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  page.on('dialog', (dialog) => dialog.accept())
  await page.goto('/')
  await page.getByRole('button', { name: '选择并确认保存位置' }).click()
  await page.getByRole('button', { name: '数据与设置', exact: true }).click()
  await page.getByRole('button', { name: '深色模式', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: '数据与设置', exact: true }).click()
  await expect(page.getByRole('button', { name: '深色模式', exact: true })).toHaveAttribute(
    'aria-pressed',
    'true'
  )
  await page.getByRole('button', { name: '浅色模式', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: '数据与设置', exact: true }).click()
  await page.getByRole('button', { name: '深色模式', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: '载入公开测试数据' }).click()
  await page.getByRole('button', { name: '确认覆盖并导入' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: /第一场：灯塔线索/ }).click()
  await page.getByRole('searchbox', { name: '搜索整场正文' }).fill('灯塔')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.locator('.search-target')).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/search-dark-320.png' })
})
