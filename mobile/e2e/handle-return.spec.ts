import { acceptAppConfirmations } from './helpers'
import { expect, test } from '@playwright/test'
import { expandModules } from './helpers'

test('仅手柄直接拖动排序，卡片长按多选不参与排序', async ({ page }, testInfo) => {
  page.on('dialog', (dialog) => dialog.accept())
  await acceptAppConfirmations(page)
  await page.goto('/')
  await page.getByRole('button', { name: '选择并确认保存位置' }).click()
  await page.getByRole('button', { name: '载入公开测试数据' }).click()
  await page.getByRole('button', { name: '确认覆盖并导入' }).click()
  await expandModules(page)
  const rows = page.locator('.record-list .gesture-row')
  const handle = rows.first().getByRole('button', { name: /拖动排序/ })
  await expect(handle).toBeVisible()
  await handle.scrollIntoViewIfNeeded()
  const a = (await handle.boundingBox())!
  const b = (await rows.nth(1).boundingBox())!
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
  await page.mouse.down()
  // 手柄没有半秒长按门槛；从专用区域开始即可直接拖动。
  await page.mouse.move(a.x + a.width / 2, b.y + 25, { steps: 10 })
  const scrollBeforeRelease = await page.evaluate(() => scrollY)
  await page.mouse.up()
  await expect(page.getByRole('status')).toContainText('排序已保存')
  await expect(rows.first()).toContainText('第二场')
  expect(await page.evaluate(() => scrollY)).toBeCloseTo(scrollBeforeRelease, 0)
  await page.screenshot({ path: testInfo.outputPath('handle-navigation-preview.png') })
  await expect(page.locator('.selection-check')).toHaveCount(0)
  await rows.first().scrollIntoViewIfNeeded()
  const body = (await rows.first().locator('.record-card').boundingBox())!
  await page.mouse.move(body.x + 60, body.y + 20)
  await page.mouse.down()
  await page.waitForTimeout(550)
  await page.mouse.up()
  await expect(page.getByLabel('选择 第二场：手动调查笔记')).toBeChecked()
  await expect(rows.first()).toContainText('第二场')
})

test('统一返回入口返回详情并保留编辑丢弃确认', async ({ page }) => {
  page.on('dialog', (dialog) => dialog.accept())
  await acceptAppConfirmations(page)
  await page.goto('/')
  await page.getByRole('button', { name: '选择并确认保存位置' }).click()
  await page.getByRole('button', { name: '载入公开测试数据' }).click()
  await page.getByRole('button', { name: '确认覆盖并导入' }).click()
  await expandModules(page)
  await page.locator('.record-card').first().click()
  const back = page.getByRole('button', { name: '返回上一页', exact: true })
  await expect(back).toBeVisible()
  await expect(back).toHaveText('')
  await expect(back.locator('svg')).toBeVisible()
  expect(await back.evaluate((button) => getComputedStyle(button).borderTopWidth)).toBe('0px')
  await page.getByRole('button', { name: '编辑场次', exact: true }).click()
  await page.getByLabel('场次名称', { exact: true }).fill('不应保存的改名')
  const confirmation = page.getByRole('dialog', { name: '确认操作', exact: true })
  await page.removeLocatorHandler(confirmation)
  await back.click()
  await expect(confirmation).toContainText('放弃尚未保存')
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByLabel('场次名称', { exact: true })).toHaveValue('不应保存的改名')
  await back.click()
  await confirmation.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑场次', exact: true })).toBeVisible()
  await back.click()
  await expect(page.getByRole('heading', { name: '跑团记录汇总', exact: true })).toBeVisible()
  await expect(page.locator('[data-module-toggle]')).toHaveCount(2)
  await page.getByRole('button', { name: '角色卡', exact: true }).click()
  await back.click()
  await expect(page.getByRole('heading', { name: '跑团记录汇总', exact: true })).toBeVisible()
})
