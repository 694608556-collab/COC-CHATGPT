import { expect, test } from '@playwright/test'
import { acceptAppConfirmations, expandModules } from './helpers'

test('模组搜索只在放大镜或键盘提交后执行，任意编辑恢复放大镜，清空取消', async ({ page }) => {
  page.on('dialog', (dialog) => dialog.accept())
  await acceptAppConfirmations(page)
  await page.goto('/')
  await page.getByRole('button', { name: '选择并确认保存位置' }).click()
  await page.getByRole('button', { name: '载入公开测试数据' }).click()
  await page.getByRole('button', { name: '确认覆盖并导入' }).click()
  await expandModules(page)
  const module = page.locator('.module-group').first()
  const field = module.getByRole('searchbox', { name: '搜索该模组所有场次正文' })
  const clear = module.getByRole('button', { name: '清空模组正文搜索' })
  const submit = module.getByRole('button', { name: '搜索模组正文', exact: true })
  const results = module.getByRole('region', { name: '模组正文搜索结果' })
  await expect(clear).toHaveCount(0)
  await expect(submit).toHaveCount(0)
  await field.fill('灯塔')
  await expect(submit).toBeVisible()
  await expect(clear).toHaveCount(0)
  await page.waitForTimeout(350)
  await expect(results).toHaveCount(0)
  const searchSize = await submit.boundingBox()
  await submit.click()
  await expect(results).toContainText('匹配')
  await expect(clear).toBeVisible()
  await expect(submit).toHaveCount(0)
  const clearSize = await clear.boundingBox()
  expect(clearSize!.width).toBe(searchSize!.width)
  expect(clearSize!.height).toBe(searchSize!.height)
  await field.fill('铜钥匙')
  await expect(submit).toBeVisible()
  await expect(results).toHaveCount(0)
  await field.fill('灯塔')
  await expect(submit).toBeVisible()
  await expect(clear).toHaveCount(0)
  await field.press('Enter')
  await expect(results).toContainText('匹配')
  await expect(clear).toBeVisible()
  await clear.click()
  await expect(field).toHaveValue('')
  await expect(clear).toHaveCount(0)
  await expect(submit).toHaveCount(0)
  await expect(results).toHaveCount(0)
})

test('整场正文搜索同样主动提交，清空取消高亮，任意编辑重新显示同尺寸放大镜', async ({ page }) => {
  page.on('dialog', (dialog) => dialog.accept())
  await acceptAppConfirmations(page)
  await page.goto('/')
  await page.getByRole('button', { name: '选择并确认保存位置' }).click()
  await page.getByRole('button', { name: '载入公开测试数据' }).click()
  await page.getByRole('button', { name: '确认覆盖并导入' }).click()
  await expandModules(page)
  await page.getByRole('button', { name: /雾港调查.*第一场：灯塔线索/ }).click()
  const field = page.getByRole('searchbox', { name: '搜索整场正文' })
  const clear = page.getByRole('button', { name: '清空正文搜索', exact: true })
  const submit = page.getByRole('button', { name: '搜索整场正文', exact: true })
  const results = page.getByRole('region', { name: '搜索结果', exact: true })
  await expect(clear).toHaveCount(0)
  await expect(submit).toHaveCount(0)
  await field.fill('灯塔')
  await expect(submit).toBeVisible()
  await expect(results).toHaveCount(0)
  const size = await submit.boundingBox()
  await submit.click()
  await expect(results).toContainText('匹配 3 条')
  await expect(page.locator('[data-message-index="4"]')).toBeFocused()
  const clearedSize = await clear.boundingBox()
  expect(clearedSize!.width).toBe(size!.width)
  expect(clearedSize!.height).toBe(size!.height)
  await field.fill('a+b')
  await expect(submit).toBeVisible()
  await expect(results).toHaveCount(0)
  await expect(page.locator('.messages mark')).toHaveCount(0)
  await field.press('Enter')
  await expect(results).toContainText('匹配 1 条')
  await clear.click()
  await expect(field).toHaveValue('')
  await expect(submit).toHaveCount(0)
  await expect(clear).toHaveCount(0)
  await expect(results).toHaveCount(0)
})
